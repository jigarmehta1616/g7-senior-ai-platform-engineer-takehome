  account_id   TEXT    NOT NULL,
  month        TEXT    NOT NULL,          -- YYYY-MM
  protected_tb REAL    NOT NULL,
  api_calls    INTEGER NOT NULL,
  active_users INTEGER NOT NULL,
  PRIMARY KEY (account_id, month)
);
